im,d=canvas(1900,2300)
label(d,(950,45),'LIBRARY SYSTEM — USE CASES',38,70)
def panel(y,height,title,actor_name,cases):
    d.rectangle((410,y,1820,y+height),outline=INK,width=3)
    label(d,(1115,y+38),title,30,70)
    actor(d,180,y+height/2-35,actor_name)
    for j,t in enumerate(cases):
        col=j%2;row=j//2;x=790+col*680;cy=y+120+row*140
        box(d,x,cy,600,100,t,'oval',29)
        # Route right-column associations through the gap above each row.
        if col==0:
            d.line([(225,y+height/2-35),(375,y+height/2-35),(375,cy),(x-300,cy)],fill=GRAY,width=2)
        else:
            d.line([(225,y+height/2-35),(350,y+height/2-35),(350,cy-63),(x,cy-63),(x,cy-50)],fill=GRAY,width=2)
panel(100,210,'Public access','Public visitor',['Search catalog / view details'])
